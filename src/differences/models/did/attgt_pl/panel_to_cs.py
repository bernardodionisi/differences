def _preprocess_covariates(
        is_panel: bool,
        base_delta: Literal["base", "delta", "both"] | dict[str, list[str]],
        y_matrix
) -> None:
    if is_panel:  # y_matrix is available only if is_panel

        # includes y if in (x) specification (as a control)
        x_covariates = data_matrix.columns

        x_base, x_delta = x_covariates, []

        if base_delta == "delta" or isinstance(base_delta, dict):

            # identify time varying Xs (only if needed: when delta is requested)
            time_varying_x = find_time_varying_covars(
                data=data_matrix,
                # do not include y (in case it is controlled for)
                covariates=[c for c in data_matrix.columns if c != y_column],
            )

            x_covariates, x_base, x_delta = pre_process_base_delta(
                base_delta=base_delta,
                x_columns=x_covariates,
                x_time_varying_columns=time_varying_x,
            )

            delta_to_create, _ = delta_col_to_create(
                x_delta=x_delta, x_base=x_base
            )

            if delta_to_create:  # these will be created by p2c later
                x_covariates.extend([f"delta_{c}" for c in delta_to_create])

        # need to copy y as delta_y in case y is among the controls (as base period y),
        # if y is among the controls it is added by x_formula to _data_matrix

        data_matrix[f"delta_{y_column}"] = y_matrix

        y_column = f"delta_{y_column}"

    else:  # repeated_cross_section (or panel as rc, is_panel is set to False)

        # list all Xs generated by model_matrix; excluding y which was included in x_formula
        x_covariates = [x for x in data_matrix.columns if x != y_column]
        x_base, x_delta = x_covariates, []

    x_base_delta = {"base": x_base, "delta": x_delta}
