# TODO: make sure Intercept is not excluded when needed
def pre_process_base_delta(
        base_delta: str | list | dict,
        x_columns: list,
        x_time_varying_columns: list,
        intercept_column: str = "Intercept",
) -> tuple:
    """
    extract x_base & x_delta from x_covariates

    Examples
    --------

    x_covariates = ['Intercept', 'a', 'b', 'c_tv', 'd_tv']
    time_varying_x = ['c_tv', 'd_tv']

    preprocess_base_delta('base', x_covariates, time_varying_x)
    preprocess_base_delta('delta', x_covariates, time_varying_x)
    preprocess_base_delta(['delta'], x_covariates, time_varying_x)

    x_covariates, x_base, x_delta = preprocess_base_delta(
        base_delta={'base': ['d_tv', 'b'], 'delta': ['c_tv', 'a']},
        x_covariates=x_covariates,
        time_varying_x=['c_tv', 'd_tv'])

    Parameters
    ----------
    base_delta
    x_columns
    x_time_varying_columns
    intercept_column

    Returns
    -------

    """
    has_intercept = bool([i for i in x_columns if i == intercept_column])

    x_columns = [i for i in x_columns if i != intercept_column]

    if isinstance(base_delta, str) or isinstance(base_delta, list):
        if "base" in base_delta and "delta" in base_delta:
            # all the covariates used as base and all the time varying covariates used as delta
            x_base, x_delta = x_columns, x_time_varying_columns

        elif "base" in base_delta:
            x_base, x_delta = x_columns, []

        else:  # delta only
            x_base, x_delta = [], x_time_varying_columns

            dropped_cols = [i for i in x_columns if i not in x_time_varying_columns]
            if dropped_cols:
                warn(
                    f"if base_delta = delta only time varying covariates will be used: "
                    f"{dropped_cols}, which were generated by x_formula, were ignored"
                )

    else:  # if a dictionary is passed

        x_base = base_delta.get("base")
        x_delta = base_delta.get("delta")

        if x_base and x_delta is None:
            # use only the requested base + all the time varying as delta

            x_delta = x_time_varying_columns

            missing_cols = [i for i in x_columns if i not in x_base + x_delta]

        elif x_delta and x_base is None:
            # use only the requested delta + all the covariates as base

            x_base = x_columns

            missing_cols = []

        else:  # both base and delta
            non_tv_x_delta = [i for i in x_delta if i not in x_time_varying_columns]

            if non_tv_x_delta:
                warn(
                    f'when specifying base_delta the list for "delta" was restricted and '
                    f"{non_tv_x_delta}, which were generated by x_formula, "
                    f"were ignored because non-time-varying"
                )

            x_delta = [i for i in x_delta if i in x_time_varying_columns]

            missing_cols = [i for i in x_columns if i not in x_base + x_delta]

        if missing_cols:
            warn(
                f"when specifying base_delta the analysis was restricted "
                f"to the requested columns and {missing_cols}, "
                f"which were generated by x_formula, have been ignored"
            )

        non_existing_cols = [i for i in x_base + x_delta if i not in x_columns]
        if non_existing_cols:
            raise ValueError(f"{non_existing_cols} missing from data matrix")

    if has_intercept:
        x_base = [intercept_column] + x_base
        x_columns = [intercept_column] + x_columns

    # new covariates may be less than initial covariates
    x_columns = [i for i in x_columns if i in set(x_base + x_delta)]

    return x_columns, x_base, x_delta


def delta_col_to_create(x_delta: list, x_base: list, return_idx: bool = False):
    """helper function for panel_2_cross_section_did

    identifies which columns to create with a prefix of 'delta_'
    """
    delta_to_create, create_idx, delta_to_replace, replace_idx = [], [], [], []

    for i, x in enumerate(x_delta):
        if x in x_base:
            delta_to_create.append(x)
            create_idx.append(i)
        else:
            delta_to_replace.append(x)
            replace_idx.append(i)
    if return_idx:
        return delta_to_create, create_idx, delta_to_replace, replace_idx
    else:
        return delta_to_create, delta_to_replace
